import streamlit as st
import pandas as pd
import matplotlib.pyplot as plt

st.set_page_config(page_title="Dashboard Pokémon", layout="wide")

if "df_poke" not in st.session_state:
    st.session_state["df_poke"] = None


def obtener_datos_filtrados():
    df = st.session_state["df_poke"].copy()

    gen_sel = st.session_state["filtro_gen"]
    if gen_sel != "Todas":
        df = df[df["Generation"] == gen_sel]

    tipo1_sel = st.session_state["filtro_tipo1"]
    if tipo1_sel != "Todos":
        df = df[df["Type 1"] == tipo1_sel]

    tipo2_sel = st.session_state["filtro_tipo2"]
    if tipo2_sel != "Todos":
        df = df[df["Type 2"] == tipo2_sel]

    cat_sel = st.session_state["filtro_cat"]
    if cat_sel == "Solo Legendarios":
        df = df[df["Legendary"] == True]
    elif cat_sel == "No Legendarios":
        df = df[df["Legendary"] == False]

    min_total = st.session_state["filtro_total"]
    df = df[df["Total"] >= min_total]

    return df


def pagina_explorar():
    st.title("Explorar Pokémon")
    st.markdown(
        "**Propósito:** Explorar estadísticas base de Pokémon según generación, tipo elemental, "
        "categoría legendaria y puntaje total.\n\n"
        "**Instrucciones de uso:** Sube el archivo `Pokemon.csv`, haz clic en **Cargar datos**, "
        "ajusta los filtros de la barra lateral y revisa los indicadores, gráficos y tabla.\n\n"
        "**Fuente de datos:** [Pokemon with stats - Kaggle](https://www.kaggle.com/datasets/abcsds/pokemon)"
    )

    archivo = st.file_uploader("Selecciona Pokemon.csv", type=["csv"])

    if st.button("Cargar datos"):
        if archivo is not None:
            df = pd.read_csv(archivo)
            # Revisión de duplicados, tratamiento de faltantes y tipos numéricos
            df = df.drop_duplicates(subset=["Name"])
            df["Type 2"] = df["Type 2"].fillna("Sin segundo tipo")
            cols_num = ["Total", "HP", "Attack", "Defense", "Sp. Atk", "Sp. Def", "Speed", "Generation"]
            for col in cols_num:
                df[col] = pd.to_numeric(df[col], errors="coerce")
            df = df.dropna(subset=cols_num)
            st.session_state["df_poke"] = df
            st.success(f"{len(df)} registros cargados y preparados.")
        else:
            st.warning("Selecciona el archivo Pokemon.csv y pulsa 'Cargar datos'.")

    if st.session_state["df_poke"] is None:
        st.info("Sube Pokemon.csv y pulsa 'Cargar datos' para comenzar.")
        return

    df = obtener_datos_filtrados()

    col1, col2, col3, col4 = st.columns(4)
    col1.metric("Pokémon filtrados", len(df))
    col2.metric("Legendarios", int(df["Legendary"].sum()) if len(df) > 0 else 0)
    col3.metric("No legendarios", int((~df["Legendary"]).sum()) if len(df) > 0 else 0)
    col4.metric("Total promedio", f"{df['Total'].mean():.1f} pts" if len(df) > 0 else "0.0 pts")

    tab_graficos, tab_datos = st.tabs(["Gráficos", "Datos"])

    with tab_graficos:
        if len(df) > 0:
            # 1. Gráfico de barras horizontales
            c1, c2, c3, c4 = st.columns(4)
            with c1:
                stat_elegida = st.selectbox(
                    "Estadística",
                    ["Total", "HP", "Attack", "Defense", "Sp. Atk", "Sp. Def", "Speed"]
                )
            with c2:
                agrupar_por = st.selectbox(
                    "Agrupar por",
                    ["Type 1", "Type 2", "Generation", "Legendary"]
                )
            with c3:
                filtro_grafico_leg = st.selectbox(
                    "Mostrar en gráfico",
                    ["Todos", "Solo Legendarios", "No Legendarios"]
                )
            with c4:
                color_grafico = st.color_picker("Color de barras", "#3b82f6")

            df_graf = df.copy()
            if filtro_grafico_leg == "Solo Legendarios":
                df_graf = df_graf[df_graf["Legendary"] == True]
            elif filtro_grafico_leg == "No Legendarios":
                df_graf = df_graf[df_graf["Legendary"] == False]

            if len(df_graf) > 0:
                resumen = df_graf.groupby(agrupar_por)[stat_elegida].mean().sort_values()
                etiquetas = resumen.index.map(
                    lambda x: "Legendario" if x is True else ("No legendario" if x is False else str(x))
                )

                fig, ax = plt.subplots(figsize=(8, 4))
                ax.barh(etiquetas, resumen.values, color=color_grafico)
                ax.set_xlabel(f"Promedio de {stat_elegida} (puntos base)")
                ax.set_ylabel(agrupar_por)
                ax.set_title(f"{stat_elegida} promedio por {agrupar_por}")
                st.pyplot(fig)
                st.caption(
                    f"Hallazgo: El grupo con mayor promedio en {stat_elegida} dentro de la selección es "
                    f"'{etiquetas.iloc[-1]}' con {resumen.values[-1]:.1f} puntos base."
                )
            else:
                st.warning("No hay Pokémon para esa opción en el gráfico.")

            st.subheader("Comparación entre dos estadísticas (Gráfico de dispersión)")
            sc1, sc2, sc3 = st.columns(3)
            with sc1:
                eje_x = st.selectbox("Eje X", ["Attack", "Defense", "Sp. Atk", "Sp. Def", "Speed", "HP"], index=0)
            with sc2:
                eje_y = st.selectbox("Eje Y", ["Defense", "Attack", "Sp. Atk", "Sp. Def", "Speed", "HP"], index=1)
            with sc3:
                color_disp = st.color_picker("Color de puntos", "#ef4444")

            fig2, ax2 = plt.subplots(figsize=(8, 4))
            ax2.scatter(df[eje_x], df[eje_y], alpha=0.7, color=color_disp, label=f"{eje_x} vs {eje_y}")
            ax2.set_xlabel(f"{eje_x} (puntos base)")
            ax2.set_ylabel(f"{eje_y} (puntos base)")
            ax2.set_title(f"{eje_x} vs {eje_y}")
            ax2.grid(True, linestyle="--", alpha=0.3)
            ax2.legend()
            st.pyplot(fig2)

            # 3. Tercer tipo de gráfico distinto: Histograma
            st.subheader("Distribución de estadística (Histograma)")
            h1, h2 = st.columns(2)
            with h1:
                stat_hist = st.selectbox(
                    "Variable del histograma",
                    ["Total", "HP", "Attack", "Defense", "Sp. Atk", "Sp. Def", "Speed"],
                    index=6
                )
            with h2:
                bins_hist = st.slider("Número de intervalos (bins)", min_value=5, max_value=30, value=15)

            fig3, ax3 = plt.subplots(figsize=(8, 3.8))
            ax3.hist(df[stat_hist], bins=bins_hist, color="#10b981", edgecolor="black")
            ax3.set_xlabel(f"{stat_hist} (puntos base)")
            ax3.set_ylabel("Cantidad de Pokémon (frecuencia)")
            ax3.set_title(f"Distribución de {stat_hist}")
            st.pyplot(fig3)
            st.caption(
                f"Hallazgo: En el subconjunto filtrado, {stat_hist} tiene una mediana de "
                f"{df[stat_hist].median():.1f} puntos base."
            )
        else:
            st.warning("No hay Pokémon con esos filtros.")

    with tab_datos:
        busqueda = st.text_input("Buscar por nombre", "")
        df_tabla = df[df["Name"].str.contains(busqueda, case=False, na=False)] if busqueda else df

        if st.checkbox("Mostrar solo columnas principales"):
            cols = ["#", "Name", "Type 1", "Type 2", "Generation", "Total", "HP", "Attack", "Defense", "Speed", "Legendary"]
            st.dataframe(df_tabla[cols], use_container_width=True, hide_index=True)
        else:
            st.dataframe(df_tabla, use_container_width=True, hide_index=True)

        csv_descarga = df_tabla.to_csv(index=False).encode("utf-8")
        st.download_button(
            label="Descargar selección CSV",
            data=csv_descarga,
            file_name="pokemon_filtrado.csv",
            mime="text/csv"
        )


def pagina_comparar_pokemon():
    st.title("Comparar Pokémon")

    if st.session_state["df_poke"] is None:
        st.info("Primero carga los datos en 'Explorar Pokémon'.")
        return

    df = obtener_datos_filtrados()

    if len(df) == 0:
        st.warning("No hay Pokémon con los filtros actuales.")
        return

    nombres = sorted(df["Name"].unique())
    p1 = st.selectbox("Pokémon 1", nombres, index=0)
    p2 = st.selectbox("Pokémon 2", nombres, index=min(1, len(nombres) - 1))

    fila1 = df[df["Name"] == p1].iloc[0]
    fila2 = df[df["Name"] == p2].iloc[0]

    c1, c2 = st.columns(2)
    c1.info(
        f"**{p1}** | Tipo 1: {fila1['Type 1']} | Tipo 2: {fila1['Type 2']} | "
        f"Gen: {fila1['Generation']} | Legendario: {'Sí' if fila1['Legendary'] else 'No'}"
    )
    c2.info(
        f"**{p2}** | Tipo 1: {fila2['Type 1']} | Tipo 2: {fila2['Type 2']} | "
        f"Gen: {fila2['Generation']} | Legendario: {'Sí' if fila2['Legendary'] else 'No'}"
    )

    stats_cols = ["HP", "Attack", "Defense", "Sp. Atk", "Sp. Def", "Speed"]
    df_comp = pd.DataFrame({
        p1: fila1[stats_cols].values,
        p2: fila2[stats_cols].values
    }, index=stats_cols)

    st.bar_chart(df_comp)
    st.dataframe(df_comp, use_container_width=True)


pag_explorar = st.Page(pagina_explorar, title="Explorar Pokémon")
pag_comparar = st.Page(pagina_comparar_pokemon, title="Comparar Pokémon")

pg = st.navigation([pag_explorar, pag_comparar])

with st.sidebar:
    st.title("Filtros Pokémon")

    if st.session_state["df_poke"] is not None:
        df_base = st.session_state["df_poke"]
        gens = ["Todas"] + sorted(df_base["Generation"].unique().tolist())
        tipos1 = ["Todos"] + sorted(df_base["Type 1"].unique().tolist())
        tipos2 = ["Todos"] + sorted(df_base["Type 2"].unique().tolist())
        min_tot = int(df_base["Total"].min())
        max_tot = int(df_base["Total"].max())
    else:
        gens = ["Todas"]
        tipos1 = ["Todos"]
        tipos2 = ["Todos"]
        min_tot = 180
        max_tot = 800

    st.selectbox("Generación", gens, key="filtro_gen")
    st.selectbox("Tipo principal", tipos1, key="filtro_tipo1")
    st.selectbox("Segundo tipo", tipos2, key="filtro_tipo2")
    st.radio("¿Es legendario?", ["Todos", "Solo Legendarios", "No Legendarios"], key="filtro_cat")
    st.slider("Estadística Total mínima", min_value=min_tot, max_value=max_tot, value=min_tot, step=10, key="filtro_total")

pg.run()